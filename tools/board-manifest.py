"""List the images Ayelet dropped into assets/board/ (and materials/) into js/board-manifest.js."""
import pathlib, json
root = pathlib.Path(__file__).resolve().parent.parent
d = root / 'assets/board'; ext = {'.jpg', '.jpeg', '.png', '.webp', '.gif'}
imgs = sorted(str(p.relative_to(root)) for p in d.glob('*') if p.suffix.lower() in ext)
mats = {p.stem: str(p.relative_to(root)) for p in (d / 'materials').glob('*') if p.suffix.lower() in ext}
(root / 'js/board-manifest.js').write_text('/* GENERATED by tools/board-manifest.py from assets/board/. */\nwindow.BOARD = ' + json.dumps({'images': imgs, 'materials': mats}) + ';\n')
print(len(imgs), 'images;', 'materials:', ', '.join(mats) or 'none')
