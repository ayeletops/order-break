"""List the images Ayelet dropped into assets/board/ (and materials/) into js/board-manifest.js, with each image's height/width."""
import pathlib, json
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
d = root / 'assets/board'; ext = {'.jpg', '.jpeg', '.png', '.webp', '.gif'}
imgs = []
for p in sorted(d.glob('*')):
    if p.suffix.lower() in ext:
        w, h = Image.open(p).size; imgs.append([str(p.relative_to(root)), round(h / w, 3)])
mats = {p.stem: str(p.relative_to(root)) for p in (d / 'materials').glob('*') if p.suffix.lower() in ext}
(root / 'js/board-manifest.js').write_text('/* GENERATED by tools/board-manifest.py from assets/board/. [path, height/width] */\nwindow.BOARD = ' + json.dumps({'images': imgs, 'materials': mats}) + ';\n')
print(len(imgs), 'images;', 'materials:', ', '.join(mats) or 'none')
