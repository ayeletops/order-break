"""Derive the grid family from 8 birthdays.
Reads secrets/dates.rtf and secrets/grid-seed.txt (both git-ignored); writes css/grids.css.
Only derived values are written. Person order is shuffled per grid with a secret seed,
so the public values can't be re-linked into dates.
Method (public, documented in docs/process/log.md):
  Cover        -> days   (1-31) as fr units for 8 columns
  Latent Field -> ages   as ring radii (normalised to the oldest)
  Work         -> birth years: gaps between sorted years as horizontal intervals
  Black Holes  -> months (1-12) placed on a 12-column year; month value = void size
  Family       -> baseline, margins, type-scale ratio from aggregates
"""
import re, random, datetime, math, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
txt = (root/'secrets/dates.rtf').read_text(errors='ignore')
seed = (root/'secrets/grid-seed.txt').read_text().strip()
ds = [(int(d), int(m), int(y) if len(y) == 4 else 1900+int(y))
      for d, m, y in re.findall(r'(\d{1,2})/(\d{1,2})/(\d{2,4})', txt)]
assert len(ds) == 8, len(ds)
today = datetime.date(2026, 11, 15)  # fixed so the grid doesn't drift daily
ages = [today.year - y - ((today.month, today.day) < (m, d)) for d, m, y in ds]
rng = random.Random(seed)
def shuf(v, tag):
    v = list(v); random.Random(seed + tag).shuffle(v); return v
days   = shuf([d for d, m, y in ds], 'cover')
agesS  = shuf(ages, 'field')
years  = sorted(y for d, m, y in ds)
gaps   = [b - a for a, b in zip(years, years[1:])]
gaps   = [g if g > 0 else 1 for g in gaps]          # twins/same-year -> 1
months = shuf([m for d, m, y in ds], 'holes')
# family constants
ratio    = round(math.sqrt(sum(d for d,_,_ in ds) / sum(m for _,m,_ in ds)), 3)  # sqrt(mean day / mean month)
baseline = round(sum(ages) / len(ages) / 2)                                       # px
margin_l = round(min(ages) / max(ages) * 100) / 10                                # vw
margin_r = round(margin_l * ratio, 1)
gutter   = round(baseline / 2)
css = f"""/* GENERATED by tools/derive-grids.py. Do not edit by hand.
   Derived from 8 birthdays (never committed). Person order shuffled per grid with a secret seed. */
:root {{
  --baseline: {baseline}px;
  --gutter: {gutter}px;
  --margin-l: {margin_l}vw;
  --margin-r: {margin_r}vw;
  --scale: {ratio};
  --cover-cols: {' '.join(f'{d}fr' for d in days)};
  --work-intervals: {' '.join(f'{g}fr' for g in gaps)};
}}
/* Latent Field rings: radius as % of the oldest */
{chr(10).join(f'.ring-{i+1} {{ --r: {round(a/max(ages)*100,1)}%; }}' for i, a in enumerate(agesS))}
/* Black Holes: 12-column year; each person's month = column + void size */
{chr(10).join(f'.hole-{i+1} {{ --col: {m}; --size: {m}; }}' for i, m in enumerate(months))}
"""
(root/'css/grids.css').write_text(css)

# PLACEMENT — the break. A one-way hash of the dates + secret seed becomes a fixed stream of offsets.
# Public: only the offsets (in [-1, 1]) and a derived integer seed. Not reversible to dates.
import hashlib, json
stream = b''
k = 0
while len(stream) < 512:
    stream += hashlib.sha256(f"{seed}|{ds}|{k}".encode()).digest(); k += 1
offs = [[round(stream[i] / 127.5 - 1, 3), round(stream[i + 1] / 127.5 - 1, 3)] for i in range(0, 256, 2)]
pseed = int.from_bytes(hashlib.sha256(f"{seed}|{ds}|seed".encode()).digest()[:4], 'big') % 2147483646 + 1
(root/'js/placement.js').write_text("/* GENERATED by tools/derive-grids.py. The break: offsets from a one-way hash of the secret dates. No dates. */\n"
    f"window.PLACEMENT = {{ seed: {pseed}, offsets: {json.dumps(offs)} }};\n")

sheet = root/'docs/grids/grid-sheet.html'
if sheet.exists():
    h = sheet.read_text(); a, b = '/*GRIDS-START*/', '/*GRIDS-END*/'
    sheet.write_text(h[:h.index(a)+len(a)] + css + h[h.index(b):])
print(css)
